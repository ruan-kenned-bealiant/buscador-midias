def _fold_function() -> sql.Composed:
    """``bm_fold``: minúsculas e sem acento, sem depender de extensão do servidor."""
    letters = [
        chr(code)
        for code in range(128, 592)
        if len(unidecode(chr(code))) == 1 and unidecode(chr(code)).isascii()
    ]
    body = sql.SQL("SELECT lower(translate(value,{},{}))").format(
        sql.Literal("".join(letters)), sql.Literal("".join(unidecode(c) for c in letters))
    )
    return sql.SQL(
        "CREATE OR REPLACE FUNCTION bm_fold(value TEXT) RETURNS TEXT "
        "LANGUAGE SQL IMMUTABLE STRICT AS {}"
    ).format(sql.Literal(body.as_string()))


def install(db: psycopg.Connection[Any]) -> None:
    """Cria o que falta no schema do ``search_path``; repetir é seguro e não altera dados."""
    db.execute("SELECT pg_advisory_xact_lock(%s)", (INSTALL_LOCK,))
    db.execute(CATALOG_DDL)
    db.execute(ENGINE_DDL)
    db.execute(_fold_function())
