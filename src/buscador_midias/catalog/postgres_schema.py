"""DDL PostgreSQL do gerenciador, portável para futuras migrations do powerDD."""

DDL = """
CREATE TABLE mechanisms (
 model TEXT PRIMARY KEY, parameters JSONB NOT NULL, version INTEGER NOT NULL DEFAULT 1,
 updated_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE sites (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, identity TEXT NOT NULL UNIQUE,
 name TEXT NOT NULL, url TEXT NOT NULL, country TEXT NOT NULL DEFAULT '',
 language TEXT NOT NULL DEFAULT '', notes TEXT NOT NULL DEFAULT '',
 active SMALLINT NOT NULL DEFAULT 1 CHECK(active IN (0,1)), deleted_at TIMESTAMPTZ,
 version INTEGER NOT NULL DEFAULT 1, created_at TIMESTAMPTZ NOT NULL,
 updated_at TIMESTAMPTZ NOT NULL, origin TEXT NOT NULL DEFAULT 'manual'
);
CREATE TABLE links (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 source_id BIGINT NOT NULL REFERENCES sites(id) ON DELETE RESTRICT,
 url TEXT NOT NULL, kind TEXT NOT NULL CHECK(kind IN ('feed','sitemap')),
 label TEXT NOT NULL DEFAULT '', notes TEXT NOT NULL DEFAULT '',
 active SMALLINT NOT NULL DEFAULT 1 CHECK(active IN (0,1)), deleted_at TIMESTAMPTZ,
 version INTEGER NOT NULL DEFAULT 1, created_at TIMESTAMPTZ NOT NULL,
 updated_at TIMESTAMPTZ NOT NULL, evidence JSONB NOT NULL DEFAULT '{}',
 origin TEXT NOT NULL DEFAULT 'manual',
 model TEXT NOT NULL REFERENCES mechanisms(model) ON DELETE RESTRICT,
 last_test JSONB NOT NULL DEFAULT '{}',
 search_interval_seconds BIGINT NOT NULL DEFAULT 14400 CHECK(search_interval_seconds>0),
 UNIQUE(source_id,url)
);
CREATE INDEX link_site ON links(source_id,deleted_at);
CREATE INDEX link_mechanism ON links(model,deleted_at);
CREATE TABLE events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 entity TEXT NOT NULL, entity_id BIGINT, action TEXT NOT NULL,
 happened_at TIMESTAMPTZ NOT NULL, before_json JSONB, after_json JSONB
);
CREATE TABLE link_test_results (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 link_id BIGINT NOT NULL REFERENCES links(id) ON DELETE RESTRICT,
 model TEXT NOT NULL REFERENCES mechanisms(model) ON DELETE RESTRICT,
 test_id TEXT NOT NULL, model_version INTEGER, observed_at TIMESTAMPTZ,
 parameters JSONB NOT NULL, result JSONB NOT NULL, UNIQUE(link_id,test_id)
);
CREATE INDEX link_test_history ON link_test_results(link_id,id);
CREATE TABLE metadata (key TEXT PRIMARY KEY,value JSONB NOT NULL);
CREATE TABLE schema_migrations (version INTEGER PRIMARY KEY,applied_at TIMESTAMPTZ NOT NULL);
CREATE TABLE catalog_validation_runs (
 id TEXT PRIMARY KEY,status TEXT NOT NULL,created_at TIMESTAMPTZ NOT NULL,
 updated_at TIMESTAMPTZ NOT NULL,window_until TIMESTAMPTZ NOT NULL,
 lookback_days INTEGER NOT NULL,max_attempts INTEGER NOT NULL,
 configurations JSONB NOT NULL,detail TEXT NOT NULL DEFAULT ''
);
CREATE TABLE catalog_validation_links (
 run_id TEXT NOT NULL REFERENCES catalog_validation_runs(id),
 link_id BIGINT NOT NULL REFERENCES links(id),link_version INTEGER NOT NULL,
 source_version INTEGER NOT NULL,host TEXT NOT NULL,initial_model TEXT NOT NULL,
 state TEXT NOT NULL DEFAULT 'pending',attempts INTEGER NOT NULL DEFAULT 0,
 ready_at DOUBLE PRECISION NOT NULL DEFAULT 0,updated_at TIMESTAMPTZ NOT NULL,
 PRIMARY KEY(run_id,link_id)
);
CREATE INDEX validation_state ON catalog_validation_links(run_id,state);
CREATE TABLE catalog_validation_attempts (
 run_id TEXT NOT NULL,link_id BIGINT NOT NULL,attempt INTEGER NOT NULL,
 model TEXT NOT NULL REFERENCES mechanisms(model),outcome TEXT NOT NULL,
 usable SMALLINT NOT NULL CHECK(usable IN (0,1)),result BYTEA NOT NULL,
 created_at TIMESTAMPTZ NOT NULL,PRIMARY KEY(run_id,link_id,attempt),
 FOREIGN KEY(run_id,link_id) REFERENCES catalog_validation_links(run_id,link_id)
);
CREATE TABLE link_cadence (
 link_id BIGINT PRIMARY KEY REFERENCES links(id),
 run_id TEXT NOT NULL REFERENCES catalog_validation_runs(id),status TEXT NOT NULL,
 confidence TEXT NOT NULL,samples INTEGER NOT NULL,interval_seconds DOUBLE PRECISION,
 observation JSONB NOT NULL,updated_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE catalog_imports (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 imported_at TIMESTAMPTZ NOT NULL DEFAULT now(),source_path TEXT NOT NULL,
 manifest JSONB NOT NULL
);
"""

