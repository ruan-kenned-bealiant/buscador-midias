"""Migração dos sites do ``bm_sites`` para a tabela de fontes confiáveis do corpus."""

from __future__ import annotations

import os
from typing import Any

import psycopg
import pytest
from psycopg.rows import dict_row

from buscador_midias.db.schema import install
from buscador_midias.db.unify import unify_sites

pytestmark = pytest.mark.skipif(
    os.environ.get("BM_TEST_POSTGRES") != "1", reason="Requer PostgreSQL de teste explícito."
)

OLD_SITES = """
CREATE TABLE bm_sites (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, identity TEXT NOT NULL UNIQUE,
 name TEXT NOT NULL, url TEXT NOT NULL, country TEXT NOT NULL DEFAULT '',
 language TEXT NOT NULL DEFAULT '', notes TEXT NOT NULL DEFAULT '',
 active SMALLINT NOT NULL DEFAULT 1, deleted_at TIMESTAMPTZ, deactivated_by TEXT,
 deactivated_reason TEXT, deactivated_at TIMESTAMPTZ, version INTEGER NOT NULL DEFAULT 1,
 origin TEXT NOT NULL DEFAULT 'manual', created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
)
"""


@pytest.fixture
def legacy(db: psycopg.Connection[Any]) -> psycopg.Connection[Any]:
    """Estado de antes da unificação: ``bm_sites`` própria e FKs apontando para ela."""
    install(db)
    db.execute(OLD_SITES)
    for table in ("bm_links", "bm_run_links", "bm_articles", "bm_document_cache"):
        names = db.execute(
            "SELECT conname FROM pg_constraint WHERE contype='f' AND conrelid=%s::regclass "
            "AND confrelid='midias_ia_trusted_sources'::regclass",
            (table,),
        ).fetchall()
        for (name,) in names:
            db.execute(f"ALTER TABLE {table} DROP CONSTRAINT {name}")
        db.execute(
            f"ALTER TABLE {table} ADD FOREIGN KEY (site_id) REFERENCES bm_sites(id) "
            + ("ON DELETE CASCADE" if table == "bm_document_cache" else "ON DELETE RESTRICT")
        )
    db.execute(
        "INSERT INTO midias_ia_trusted_sources(id,name,url,url_without_https_www,country,"
        "country_code,notes,active) VALUES "
        "(10,'A oficial','https://www.a.com','a.com','Brasil','BR','curada',true),"
        "(11,'B','https://b.com','b.com','Chile','CL','',true),"
        "(12,'B repetida','https://b.com','b.com','Chile','CL','',true),"
        "(13,'C seção','https://c.com/x','c.com/x','Peru','PE','',true)"
    )
    db.execute("SELECT setval(pg_get_serial_sequence('midias_ia_trusted_sources','id'),13)")
    db.execute(
        "INSERT INTO bm_sites(id,identity,name,url,country,language,notes,active,version,origin,"
        "deleted_at,deactivated_by) VALUES "
        "(1,'a.com','A','https://a.com','','Português','minha',1,4,'mapping',NULL,NULL),"
        "(2,'b.com','B','https://b.com','',  '',  '',0,2,'manual',NULL,'health'),"
        "(3,'c.com','C','https://c.com','Peru','','',1,1,'manual',NULL,NULL),"
        "(4,'novo.com','Novo','https://novo.com','Chile','Espanhol','',1,7,'manual',now(),'user')"
    )
    db.execute("INSERT INTO bm_mechanisms(model,parameters) VALUES('rss','{}')")
    db.execute(
        "INSERT INTO bm_links(site_id,url,kind,mechanism) VALUES "
        "(1,'https://a.com/feed','feed','rss'),(2,'https://b.com/feed','feed','rss'),"
        "(4,'https://novo.com/feed','feed','rss')"
    )
    db.row_factory = dict_row  # type: ignore[assignment]
    return db


def sites(db: psycopg.Connection[Any]) -> dict[str, dict[str, Any]]:
    rows = db.execute(
        "SELECT * FROM midias_ia_trusted_sources WHERE identity IS NOT NULL"
    ).fetchall()
    return {r["identity"]: r for r in rows}


def test_a_site_adopts_the_trusted_source_with_the_same_address(legacy):
    unify_sites(legacy)
    a = sites(legacy)["a.com"]
    assert a["id"] == 10 and a["name"] == "A oficial" and a["country"] == "Brasil"
    assert (a["version"], a["origin"], a["active"]) == (4, "mapping", True)
    assert a["notes"] == "curada" and a["language"] == "Português"


def test_the_first_of_the_repeated_rows_is_adopted_and_the_other_left_alone(legacy):
    unify_sites(legacy)
    assert sites(legacy)["b.com"]["id"] == 11
    other = legacy.execute("SELECT identity,active FROM midias_ia_trusted_sources WHERE id=12")
    assert other.fetchone() == dict(identity=None, active=True)


def test_a_site_without_an_exact_match_becomes_a_new_row(legacy):
    result = unify_sites(legacy)
    c, novo = sites(legacy)["c.com"], sites(legacy)["novo.com"]
    assert c["id"] not in (13,) and c["name"] == "C" and c["url_without_https_www"] == "c.com"
    assert novo["version"] == 7 and novo["deleted_at"] is not None and novo["active"] is True
    assert novo["deactivated_by"] == "user" and novo["origin"] == "manual"
    assert (result["matched"], result["created"]) == (2, 2)


def test_our_state_wins_where_the_search_reads_a_site(legacy):
    unify_sites(legacy)
    b = sites(legacy)["b.com"]
    assert b["active"] is False and b["deactivated_by"] == "health"


def test_links_and_run_data_follow_the_new_ids(legacy):
    unify_sites(legacy)
    links = {
        r["url"]: r["site_id"]
        for r in legacy.execute("SELECT url,site_id FROM bm_links").fetchall()
    }
    ids = {k: v["id"] for k, v in sites(legacy).items()}
    assert links == {
        "https://a.com/feed": ids["a.com"],
        "https://b.com/feed": ids["b.com"],
        "https://novo.com/feed": ids["novo.com"],
    }


def test_foreign_keys_now_point_to_the_trusted_sources_and_the_old_table_is_gone(legacy):
    unify_sites(legacy)
    assert legacy.execute("SELECT to_regclass('bm_sites') IS NULL AS gone").fetchone()["gone"]
    targets = legacy.execute(
        "SELECT conrelid::regclass::text t,confrelid::regclass::text f,confdeltype d "
        "FROM pg_constraint WHERE contype='f' AND confrelid='midias_ia_trusted_sources'::regclass "
        "ORDER BY 1"
    ).fetchall()
    assert {(r["t"], r["d"]) for r in targets} == {
        ("bm_links", "r"),
        ("bm_run_links", "r"),
        ("bm_articles", "r"),
        ("bm_document_cache", "c"),
    }
    with pytest.raises(psycopg.errors.ForeignKeyViolation), legacy.transaction():
        legacy.execute(
            "INSERT INTO bm_links(site_id,url,kind,mechanism) VALUES(999,'https://x/f','feed','rss')"
        )


def test_events_of_sites_follow_the_new_ids(legacy):
    legacy.execute("INSERT INTO bm_events(entity,entity_id,action) VALUES('source',1,'update')")
    unify_sites(legacy)
    event = legacy.execute("SELECT entity_id FROM bm_events WHERE entity='source'").fetchone()
    assert event["entity_id"] == sites(legacy)["a.com"]["id"]


def test_running_it_twice_changes_nothing(legacy):
    first = unify_sites(legacy)
    snapshot = sites(legacy)
    second = unify_sites(legacy)
    assert first["migrated"] is True and second["migrated"] is False
    assert sites(legacy) == snapshot


def test_identity_stays_unique_among_the_sites_the_search_owns(legacy):
    unify_sites(legacy)
    with pytest.raises(psycopg.errors.UniqueViolation), legacy.transaction():
        legacy.execute(
            "INSERT INTO midias_ia_trusted_sources(name,url,identity) "
            "VALUES('Dup','https://a.com','a.com')"
        )
